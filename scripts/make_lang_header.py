"""Generate firmware/include/lang_names.h: the language-choice screen's words as
1-bit bitmaps, so the ESP32 can show Kannada and Hindi at power-on, before the
PC app (which renders all other non-English text) is connected.

    .\\.venv\\Scripts\\python scripts\\make_lang_header.py
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
import kiosk_text as kt  # noqa: E402

ITEMS = [  # (C name, text, px)
    ("LANG_KN", "ಕನ್ನಡ", 30),
    ("LANG_HI", "हिंदी", 30),
    ("LANG_PROMPT_KN", "ಭಾಷೆಯನ್ನು ಆಯ್ಕೆಮಾಡಿ", 18),
    ("LANG_PROMPT_HI", "भाषा चुनें", 18),
]


def bitmap(text, px):
    r = kt.Renderer(px)
    w = int(r.width(text) + 2)
    img = r.render_line(text, w)
    rows = kt.to_rows(img)
    return w, img.shape[0], b"".join(rows)


out = ["// Generated by scripts/make_lang_header.py - do not edit by hand.",
       "// 1-bit bitmaps, MSB = leftmost pixel, rows of (w + 7) / 8 bytes.",
       "#pragma once", "#include <stdint.h>", "",
       "struct LangBitmap { uint16_t w, h; const uint8_t *data; };", ""]
for name, text, px in ITEMS:
    w, h, data = bitmap(text, px)
    body = ",".join(f"0x{b:02x}" for b in data)
    out.append(f"// {text}")
    out.append(f"static const uint8_t {name}_DATA[] PROGMEM = {{{body}}};")
    out.append(f"static const LangBitmap {name} = {{{w}, {h}, {name}_DATA}};")
    out.append("")
path = ROOT / "firmware" / "include" / "lang_names.h"
path.write_text("\n".join(out), encoding="utf-8")
print(f"wrote {path} ({path.stat().st_size} bytes)")
